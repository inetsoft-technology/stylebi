package inetsoft.uql.asset.internal;


import java.util.*;

/**
 * Finds and rewrites a table's own local column references in expression-column script text --
 * {@code field['x']}, {@code field["x"]}, {@code field.x}, and the entity-qualified
 * {@code field['T.x']} form generated by range columns (Bug #78234 / WBS-104/105).
 *
 * <p>The single matcher shared by the rename rewrite ({@code RenameColumnController}) and the
 * remove pre-check ({@code WorksheetControllerService}), so the two can no longer disagree
 * about which reference syntaxes count. It is token-based, on {@link ScriptIterator}: a match is
 * a ref token whose parent token is exactly {@code field} and whose value equals one of the
 * given names exactly. That excludes text inside string literals (the iterator skips them), a
 * longer name that merely starts with the column's name ({@code field.Amount2}), and another
 * object's member ({@code Other.Amount}).</p>
 */
public final class FieldReferenceMatcher {
   private FieldReferenceMatcher() {
   }

   /**
    * True if {@code expr} reads {@code field[<name>]} / {@code field.<name>} for any of
    * {@code names}.
    */
   public static boolean references(String expr, Collection<String> names) {
      return references(expr, names, Set.of());
   }

   /**
    * As {@link #references(String, Collection)}, but a name that differs from one of
    * {@code names} only by case also counts, because the runtime column lookup falls back to an
    * ignore-case match (Bug #78679). A token that exactly equals one of {@code otherOutputNames}
    * (another column's output name) is that other column's read and never a case-different read of
    * this one -- an exact match always wins.
    */
   public static boolean references(String expr, Collection<String> names,
                                    Collection<String> otherOutputNames)
   {
      if(expr == null || expr.isEmpty() || names == null || names.isEmpty()) {
         return false;
      }

      Set<String> folded = fold(names);

      for(Piece piece : tokenize(expr)) {
         if(!piece.fieldRef) {
            continue;
         }

         String val = piece.token.val;

         if(names.contains(val)) {
            return true;
         }

         if(!isExact(val, otherOutputNames) && folded.contains(val.toLowerCase())) {
            return true;
         }
      }

      return false;
   }

   /**
    * Rewrites every {@code field[<old>]} / {@code field.<old>} reference whose name is a key of
    * {@code renames} to the mapped new name, keeping the original quoting style. A dot-form
    * reference whose new name is not a valid identifier is turned into the bracket form. Returns
    * {@code expr} unchanged (the same instance) when nothing matched, so a script the rename does
    * not touch is never re-serialized.
    */
   public static String rename(String expr, Map<String, String> renames) {
      return rename(expr, renames, Set.of());
   }

   /**
    * As {@link #rename(String, Map)}, but a reference that differs from a key of {@code renames}
    * only by case is rewritten too (the runtime resolves it ignoring case, Bug #78679); only the
    * name token is replaced, so the author's quoting and surrounding text are kept. A token that
    * exactly equals one of {@code otherOutputNames} belongs to another column and is left alone.
    */
   public static String rename(String expr, Map<String, String> renames,
                               Collection<String> otherOutputNames)
   {
      if(expr == null || expr.isEmpty() || renames == null || renames.isEmpty()) {
         return expr;
      }

      List<Piece> pieces = tokenize(expr);
      Map<String, String> foldedRenames = new HashMap<>();
      renames.forEach((k, v) -> foldedRenames.putIfAbsent(k.toLowerCase(), v));
      List<String> out = new ArrayList<>();
      boolean changed = false;

      for(Piece piece : pieces) {
         ScriptIterator.Token token = piece.token;
         String nname = null;

         if(piece.fieldRef) {
            nname = renames.get(token.val);

            if(nname == null && !isExact(token.val, otherOutputNames)) {
               nname = foldedRenames.get(token.val.toLowerCase());
            }
         }

         if(nname == null || nname.equals(token.val)) {
            out.add(token.toString());
            continue;
         }

         changed = true;

         if(token.type == ScriptIterator.Token.NORMAL_REF) {
            if(isIdentifier(nname)) {
               out.add(nname);
            }
            else {
               // field.old -> field['new name']: drop the dot emitted before this token.
               if(!out.isEmpty() && ".".equals(out.get(out.size() - 1).trim())) {
                  out.remove(out.size() - 1);
               }

               out.add(bracket(nname));
            }
         }
         else if(token.type == ScriptIterator.Token.DOUBLE_REF || nname.indexOf('\'') >= 0) {
            out.add("[\"" + nname + "\"]");
         }
         else {
            out.add("['" + nname + "']");
         }
      }

      return changed ? String.join("", out) : expr;
   }

   private static Set<String> fold(Collection<String> names) {
      Set<String> folded = new HashSet<>();

      for(String name : names) {
         folded.add(name.toLowerCase());
      }

      return folded;
   }

   private static boolean isExact(String val, Collection<String> names) {
      return names != null && names.contains(val);
   }

   private static String bracket(String name) {
      return name.indexOf('\'') >= 0 ? "[\"" + name + "\"]" : "['" + name + "']";
   }

   private static boolean isIdentifier(String name) {
      if(name.isEmpty() || !Character.isJavaIdentifierStart(name.charAt(0))) {
         return false;
      }

      for(int i = 1; i < name.length(); i++) {
         if(!Character.isJavaIdentifierPart(name.charAt(i))) {
            return false;
         }
      }

      return true;
   }

   private static List<Piece> tokenize(String expr) {
      List<Piece> pieces = new ArrayList<>();
      ScriptIterator iterator = new ScriptIterator(expr);
      iterator.addScriptListener((token, pref, cref) -> pieces.add(new Piece(
         token, token.isRef() && pref != null && FIELD.equals(pref.val))));
      iterator.iterate();
      return pieces;
   }

   private record Piece(ScriptIterator.Token token, boolean fieldRef) {
   }

   private static final String FIELD = "field";
}
