package inetsoft.uql.jdbc;

import inetsoft.test.*;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.test.context.ContextConfiguration;
import org.springframework.test.context.junit.jupiter.SpringExtension;

import java.sql.*;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Bug #81185, row comparison on Derby: a statement with time(...) returns the same rows as its
 * SQL regenerated by UniformSQL, for the two statements of the report.
 */
@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = { BaseTestConfiguration.class, PluginsTestConfiguration.class,
                                 SQLHelperNotEqualJoinTest.Config.class },
                      initializers = ConfigurationContextInitializer.class)
@SreeHome
@Tag("core")
class SQLParserTimeFunctionRowsTest {
   @Test
   void regeneratedSqlReturnsTheSameRows() throws Exception {
      String[] statements = {
         "select id from orders where order_time > time('10:00:00') order by id",
         "select id, time(order_time) as t from orders where time(order_time) > time('09:30:00') " +
            "order by id",
         "select id from orders where hour(time(order_time)) in (8, 10) order by id",
      };

      Driver driver = (Driver) Class.forName("org.apache.derby.iapi.jdbc.AutoloadedDriver")
         .getDeclaredConstructor().newInstance();

      try(Connection con = driver.connect("jdbc:derby:memory:rows81185;create=true",
                                          new Properties());
          Statement st = con.createStatement())
      {
         st.execute("create table orders (id int, order_time time)");
         st.execute("insert into orders values (1, '08:15:00'), (2, '09:45:30'), " +
                    "(3, '10:00:00'), (4, '10:30:00'), (5, '23:59:59'), (6, null)");

         for(String original : statements) {
            UniformSQL sql = new UniformSQL();
            sql.setDataSource(SQLHelperNotEqualJoinTest.RowCompare.dataSource("derby"));
            sql.parse(original, UniformSQL.PARSE_ALL, UniformSQL.PARSE_PERIOD);
            assertEquals(UniformSQL.PARSE_SUCCESS, sql.getParseResult(), original);
            assertFalse(sql.isLossy(), original);
            sql.clearSQLString();
            String regenerated = sql.getSQLString();

            List<List<String>> expected = rows(st, original);
            assertFalse(expected.isEmpty(), original);
            assertEquals(expected, rows(st, regenerated), regenerated);
         }
      }
   }

   private static List<List<String>> rows(Statement st, String sql) throws SQLException {
      List<List<String>> rows = new ArrayList<>();

      try(ResultSet rs = st.executeQuery(sql)) {
         int cols = rs.getMetaData().getColumnCount();

         while(rs.next()) {
            List<String> row = new ArrayList<>();

            for(int i = 1; i <= cols; i++) {
               row.add(rs.getString(i));
            }

            rows.add(row);
         }
      }

      return rows;
   }
}
