package inetsoft.uql.util.filereader;

import inetsoft.test.*;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ContextConfiguration;
import org.springframework.test.context.junit.jupiter.SpringExtension;

import java.util.stream.Stream;

/**
 * Replays the seed corpus in {@code csv-seeds} against {@link CSVLoaderProperties}.
 */
@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = { BaseTestConfiguration.class, SwapperTestConfiguration.class }, initializers = ConfigurationContextInitializer.class)
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
@SreeHome
@Tag("core")
class CSVLoaderSeedTest {
   @ParameterizedTest(name = "{0}")
   @MethodSource("seeds")
   void importInvariantsHold(String name, byte[] seed) throws Exception {
      CSVLoaderProperties.check(seed);
   }

   static Stream<Arguments> seeds() throws Exception {
      return SeedCorpus.load(CSVLoaderSeedTest.class, "csv-seeds");
   }
}
