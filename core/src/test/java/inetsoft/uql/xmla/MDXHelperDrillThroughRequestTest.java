import static org.junit.jupiter.api.Assertions.*;

/**
 * Bug #80104: drill-through statement generated by {@link MDXHelper} is sent through the real
 * {@link XMLAHandler} execute path to a strict-XML local endpoint; the server must see
 * well-formed XML and the true MDX (escaped exactly once).
 */
@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = { BaseTestConfiguration.class,
                                  MDXHelperDrillThroughRequestTest.CredentialConfig.class },
                      initializers = ConfigurationContextInitializer.class)
@SreeHome
@Tag("core")
class MDXHelperDrillThroughRequestTest {
   @Configuration
   static class CredentialConfig {
      @Bean
      public CredentialService credentialService() throws Exception {
         Constructor<CredentialService> ctor = CredentialService.class.getDeclaredConstructor();
         ctor.setAccessible(true);
         return ctor.newInstance();
      }
   }

   private static class TestQuery extends XMLAQuery {
      TestQuery(String cube, XNode where) {
         setCube(cube);
         this.where = where;
      }

      @Override
      public XNode getFilterNode() {
         return where;
      }

      private final XNode where;
   }

   private HttpServer server;
   private final List<String> malformed = new CopyOnWriteArrayList<>();
   private volatile String statementSeen;

   @BeforeEach
   void startServer() throws Exception {
      server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
      server.createContext("/", ex -> {
         byte[] req = ex.getRequestBody().readAllBytes();
         int code = 200;
         byte[] resp = "<r/>".getBytes(StandardCharsets.UTF_8);

         try {
            DocumentBuilderFactory f = DocumentBuilderFactory.newInstance();
            f.setNamespaceAware(true);
            Document doc = f.newDocumentBuilder().parse(new ByteArrayInputStream(req));
            NodeList stmt = doc.getElementsByTagNameNS("*", "Statement");

            if(stmt.getLength() > 0) {
               statementSeen = stmt.item(0).getTextContent();
            }
         }
         catch(Exception e) {
            malformed.add(new String(req, StandardCharsets.UTF_8));
            code = 500;
         }

         ex.sendResponseHeaders(code, resp.length);
         ex.getResponseBody().write(resp);
         ex.close();
      });
      server.start();
   }

   @AfterEach
   void stopServer() {
      server.stop(0);
   }

   private static XMLANode node(String dim, String unique, String value, boolean measure) {
      AttributeRef ref = new AttributeRef(dim, unique);

      if(measure) {
         ref.setRefType(DataRef.MEASURE);
      }

      Condition cond = new Condition();
      cond.setOperation(XCondition.EQUAL_TO);
      cond.addValue(value);
      XMLANode node = new XMLANode();
      node.setValue(new ConditionItem(ref, cond, 0));
      node.setAttribute("dimension", dim);
      return node;
   }

   private String sendDrillThrough(String cube, XNode where) throws Exception {
      XMLADataSource ds = new XMLADataSource();
      TestQuery query = new TestQuery(cube, where);
      query.setDataSource(ds);
      String stmt = new MDXHelper(query).generateDrillThrough()[0];
      ds.setURL("http://127.0.0.1:" + server.getAddress().getPort() + "/");
      ds.setCatalogName("Cat");
      ds.setDatasourceInfo("Info");
      XMLAHandler handler = new XMLAHandler();
      handler.connect(ds, new VariableTable());
      Method m = XMLAHandler.class.getDeclaredMethod(
         "execute", String.class, VariableTable.class, java.security.Principal.class,
         String.class, XMLAHandler.CancelHandler.class);
      m.setAccessible(true);
      m.invoke(handler, stmt, new VariableTable(), null, "Tabular", null);
      return stmt;
   }

   private static XMLASet and(XNode a, XNode b) {
      XMLASet set = new XMLASet(XMLASet.AND);
      set.addChild(a, false, false);
      set.addChild(b, false, false);
      return set;
   }

   @Test
   void specialCharacterNamesReachServerAsWellFormedTrueMdx() throws Exception {
      sendDrillThrough("R&D", and(node("[Dim]", "[Dim].[Name]", "[Dim].[A&B]", false),
                                  node("[Measures]", "[Measures].[Sales & Cost]", "1", true)));

      assertTrue(malformed.isEmpty(), "malformed request bodies: " + malformed);
      assertNotNull(statementSeen);
      assertTrue(statementSeen.contains("FROM [R&D]"), statementSeen);
      assertTrue(statementSeen.contains("[Measures].[Sales & Cost]"), statementSeen);
      assertTrue(statementSeen.contains("[Dim].[A&B]"), statementSeen);
      assertFalse(statementSeen.contains("&amp;"), statementSeen);
   }

   @Test
   void plainNamesAreUnchanged() throws Exception {
      String stmt = sendDrillThrough("Sales", and(
         node("[Dim]", "[Dim].[Name]", "[Dim].[East]", false),
         node("[Measures]", "[Measures].[Qty]", "1", true)));

      assertTrue(malformed.isEmpty(), "malformed request bodies: " + malformed);
      assertEquals(stmt, statementSeen);
      assertTrue(stmt.contains("FROM [Sales]") && stmt.contains("[Dim].[East]"), stmt);
   }

   @Test
   void measuresOnlyStatementIsEscapedOnce() throws Exception {
      // with no dimension the helper asks for the cube type (Mondrian check)
      Cube cubeDef = new Cube();
      cubeDef.setType(XCube.SAP);
      String stmt;

      try(MockedStatic<XMLAUtil> util = Mockito.mockStatic(XMLAUtil.class,
                                                           Mockito.CALLS_REAL_METHODS))
      {
         util.when(() -> XMLAUtil.getCube(Mockito.any(), Mockito.any())).thenReturn(cubeDef);
         stmt = sendDrillThrough("R&D",
                                 node("[Measures]", "[Measures].[Sales & Cost]", "1", true));
      }

      assertTrue(malformed.isEmpty(), "malformed request bodies: " + malformed);
      assertTrue(stmt.contains("{[Measures].[Sales &amp; Cost]} ON COLUMNS FROM [R&amp;D]"),
                 stmt);
      assertEquals("{[Measures].[Sales & Cost]} ON COLUMNS FROM [R&D]",
                   statementSeen.substring(statementSeen.indexOf("{")));
   }
}
