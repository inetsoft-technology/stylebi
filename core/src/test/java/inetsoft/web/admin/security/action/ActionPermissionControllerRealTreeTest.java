package inetsoft.web.admin.security.action;

/*
 * Bug #77251 / #77252: drives the real ActionPermissionController.setPermissions() with the real
 * ActionPermissionService.getActionTree(principal) and the real ResourcePermissionService against
 * a real security provider (no hand-built tree), in multi-tenant mode.
 *
 * view-components.json is generated by the web module's frontend build and is not on core's test
 * classpath, so view-components-snapshot.json (next to this class) is a copy of the generated file.
 * It is stored under a different name/package so ComponentAuthorizationService in other tests
 * does not pick it up.
 *
 * Personas:
 *   orgAdmin - org user holding the global "Organization Administrator" role (not a site admin)
 *   delegate - plain org user whose only grant is ACCESS on EM_COMPONENT:settings/security/actions
 *   grantee  - plain org user used as the target of a legitimate grant
 */

